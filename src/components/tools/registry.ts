/** 已注册（即已实现）的工具 slug */
export type RegisteredSlug = keyof typeof TOOL_COMPONENTS

/** 已注册的工具 slug 列表，供 check-i18n 与开发期自检 */
export const REGISTERED_SLUGS: readonly string[] = Object.keys(TOOL_COMPONENTS)

/** 该 slug 是否已实现（未实现的工具页渲染占位面板，不挂岛屿） */
export function isRegistered(slug: string): slug is RegisteredSlug {
  return slug in TOOL_COMPONENTS
}

/** 取该工具的专属文案键；未注册则返回空数组 */
export function keysFor(slug: string): readonly Key[] {
  return isRegistered(slug) ? TOOL_KEYS[slug] : []
}
