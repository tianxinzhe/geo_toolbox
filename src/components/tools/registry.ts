/**
 * slug → 工具岛屿的注册表
 *
 * 一工具一组件一文件的对应关系是硬性的（技术方案 3 章「架构要点」）。
 * 新增工具的完整清单：
 *   ① src/lib/**                              纯函数与单测
 *   ② src/components/tools/X.vue
 *   ③ 本文件注册（组件 + 专属文案键）
 *   ④ src/i18n/tools.ts                       元数据
 *   ⑤ src/i18n/ui/{lang}.ts                   界面文案
 *   ⑥ src/i18n/content/tools/{slug}/{lang}.md 文档区正文
 *
 * 用显式静态 import 而不是 import.meta.glob 的原因：
 * 组件必须在构建期被明确引用，Vite 才能为每个工具页单独切分 chunk，
 * 保证「无地图工具页首屏 ≤60KB」的体积预算（技术方案 2 章）。
 *
 * 🔑 类型说明：这里的值**不要**标注成 `Record<string, Component>`。
 * 那样会把具体组件类型擦成宽泛的 vue `Component` 联合类型，
 * Astro 的模板检查会报 ts(2604) "not a valid component"。
 * 用 `satisfies` 保留推断出的字面量类型，组件经 getStaticPaths 的 props
 * 传到页面时类型仍然是具体的 SFC 类型，client:load 才能通过检查。
 */
